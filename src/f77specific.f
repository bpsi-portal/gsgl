C
C     ****** DRAW INTEGER NUMBER ******
C
      SUBROUTINE NUMBI_DIM(I,KFORM,NCHAR,IDIM)
C
      CHARACTER KFORM*16,KSEND*24
C
      WRITE(KSEND,KFORM) I
      IF (IDIM.EQ.1) THEN
         CALL TEXT(KSEND,NCHAR)
      ELSE IF (IDIM.EQ.2) THEN
         CALL TEXT2D(KSEND,NCHAR)
      ELSE IF (IDIM.EQ.3) THEN
         CALL TEXT3D(KSEND,NCHAR)
      ENDIF
      RETURN
      END
C
C
C
      SUBROUTINE NUMBI(I,KFORM,NCHAR)
      CHARACTER KFORM*16
      CALL NUMBI_DIM(I,KFORM,NCHAR,1)
      RETURN
      END
C
C
C
      SUBROUTINE NUMBI2D(I,KFORM,NCHAR)
      CHARACTER KFORM*16
      CALL NUMBI_DIM(I,KFORM,NCHAR,2)
      RETURN
      END
C
C
C
      SUBROUTINE NUMBI3D(I,KFORM,NCHAR)
      CHARACTER KFORM*16
      CALL NUMBI_DIM(I,KFORM,NCHAR,3)
      RETURN
      END
C
C     ****** DRAW DOUBLE PRECISION REAL NUMBER ******
C
      SUBROUTINE NUMBD_DIM(D,KFORM,NCHAR,IDIM)
C
      REAL*8 D
      CHARACTER KFORM*16,KSEND*24
C
      WRITE(KSEND,KFORM) D
      N=0
    1 CONTINUE
         N=N+1
      IF(KSEND(N:N).EQ.' ') GOTO 1
C
      IF(KSEND(N:N).EQ.'-') THEN
         IF(N.GT.1.AND.KSEND(N+1:N+1).EQ.'.') THEN
            KSEND(N-1:N-1)='-'
            KSEND(N  :N  )='0'
         ENDIF
      ELSEIF(KSEND(N:N).EQ.'.') THEN
         IF(N.GT.1) THEN
            KSEND(N-1:N-1)='0'
         ENDIF
      ENDIF
C
      IF (IDIM.EQ.1) THEN
         CALL TEXT(KSEND,NCHAR)
      ELSE IF (IDIM.EQ.2) THEN
         CALL TEXT2D(KSEND,NCHAR)
      ELSE IF (IDIM.EQ.3) THEN
         CALL TEXT3D(KSEND,NCHAR)
      ENDIF
      RETURN
      END
C
C
C
      SUBROUTINE NUMBD(D,KFORM,NCHAR)
      REAL*8 D
      CHARACTER KFORM*16
      CALL NUMBD_DIM(D,KFORM,NCHAR,1)
      RETURN
      END
C
C
C
      SUBROUTINE NUMBD2D(D,KFORM,NCHAR)
      REAL*8 D
      CHARACTER KFORM*16
      CALL NUMBD_DIM(D,KFORM,NCHAR,2)
      RETURN
      END
C
C
C
      SUBROUTINE NUMBD3D(D,KFORM,NCHAR)
      REAL*8 D
      CHARACTER KFORM*16
      CALL NUMBD_DIM(D,KFORM,NCHAR,3)
      RETURN
      END
C
C     ****** DRAW REAL NUMBER ******
C
      SUBROUTINE NUMBR_DIM(R,KFORM,NCHAR,IDIM)
C
      REAL*8 D
      CHARACTER KFORM*16
C
      D=DBLE(R)
      CALL NUMBD_DIM(D,KFORM,NCHAR,IDIM)
      RETURN
      END
