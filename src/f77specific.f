      SUBROUTINE SET_F77_COMMON_GSGFX 
     &     (PXS1,PYS1,PXE1,PYE1,GXS1,GYS1,GXE1,GYE1,LGF1)
      LOGICAL LGF
      INTEGER LGF1
      COMMON /GSGFXY/ DX,DY,PXS,PYS,PXE,PYE,GXS,GYS,GXE,GYE,LGF
C
      IF (LGF1.EQ.0) THEN
         LGF = .FALSE.
      ELSE
         LGF = .TRUE.
      ENDIF
      IF (.NOT.LGF) RETURN
      PXS = PXS1
      PYS = PYS1
      PXE = PXE1
      PYE = PYE1
      GXS = GXS1
      GYS = GYS1
      GXE = GXE1
      GYE = GYE1
      DX=(PXE-PXS)/(GXE-GXS)
      DY=(PYE-PYS)/(GYE-GYS)
C
      RETURN
      END
