C
C     SAMPLE PROGRAM sample3d-4.f
C
      DIMENSION Z(101,101),X(101),Y(101)
      EXTERNAL R2G2B_17
C
      IXMAX=21
      IYMAX=21
      CALL GSOPEN
      DO I=1,IXMAX
         DO J=1,IYMAX
            X(I)=0.1*FLOAT(I-1)
            Y(J)=0.1*FLOAT(J-1)
            Z(I,J)=COS(X(I))*SIN(Y(J))
         ENDDO
      ENDDO
      ZMIN= -1.0
      ZMAX= 1.0
C
      XL=15.0
      YL=15.0
      ZL=6.0
C
      PHI=50.0
      THETA=60.0
      RADIUS=10.0
C
      CALL PAGES
      CALL SETCHS(0.50,0.0)
      CALL SETFNT(2)
C
      CALL GMNMX1(X,1,IXMAX,1,XMIN,XMAX)
      CALL GMNMX1(Y,1,IYMAX,1,YMIN,YMAX)
      CALL GQSCAL(XMIN,XMAX,GXMIN,GXMAX,XSCAL)
      CALL GQSCAL(YMIN,YMAX,GYMIN,GYMAX,YSCAL)
      CALL GQSCAL(ZMIN,ZMAX,GZMIN,GZMAX,ZSCAL)
C
      CALL GDEFIN3D(XL ,YL ,ZL, XMIN, XMAX, YMIN, YMAX, ZMIN, ZMAX)
      CALL SET3DCOORD_POLAR1 (
     &     0.5*(XMIN+XMAX), 0.5*(YMIN+YMAX), 0.5*(ZMIN+ZMAX),
     &     RADIUS, THETA, PHI)
C
      CALL GSCALE3DX( XMIN, XSCAL, 0.3, 0)
      CALL GSCALE3DY( YMIN, YSCAL, 0.3, 0)
      CALL GSCALE3DZ( 0.0,  ZSCAL, 0.3, 0)
      CALL GVALUE3DX( XMIN, XSCAL, 2, 1)
      CALL GVALUE3DY( YMIN, YSCAL, 2, 1)
      CALL GVALUE3DZ( 0.0,  ZSCAL, 2, 1)
C
      CALL PERS3D1(Z,101,IXMAX,IYMAX,8,R2G2B_17) ! Flat Shading
      CALL GAxis3D(2)
      CALL GDrawBack3D(0.3,0.3,0.3)
      CALL PAGEE
      CALL GSCLOS
      STOP
      END
