      SUBROUTINE READ_LOGICAL (I, IERROR)
      INTEGER I
      LOGICAL L
      INTEGER IERROR
C
      IERROR=0
      IF (I.EQ.0) THEN
         L = .FALSE.
      ELSE
         L = .TRUE.
      ENDIF
      READ(5,'(L1)',END=2,ERR=1) L
      IF (L) THEN
         I=1
      ELSE
         I=0
      ENDIF
      RETURN
 2    CONTINUE
      IERROR=2
      RETURN
 1    CONTINUE
      IERROR=1
      RETURN
      END
